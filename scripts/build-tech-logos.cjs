const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const directory = path.join(root, "assets", "tech-stack");
const sources = JSON.parse(fs.readFileSync(path.join(directory, "sources.json"), "utf8"));
const entries = {};

for (const { name, file } of sources) {
  const svg = fs.readFileSync(path.join(directory, file), "utf8");
  if (!svg.includes("<svg") || /<script|<foreignObject|\son[a-z]+\s*=/i.test(svg)) {
    throw new Error(`Invalid logo asset: ${name}`);
  }
  if (entries[name]) throw new Error(`Duplicate logo: ${name}`);
  entries[name] = { src: `data:image/svg+xml;base64,${Buffer.from(svg).toString("base64")}` };
}

// Embed the local assets so both canvas textures and DOM images work over file://.
const bundle = `// Generated by scripts/build-tech-logos.cjs. Sources: assets/tech-stack/sources.json.
(() => {
  const entries = ${JSON.stringify(entries, null, 2)};
  const get = (name) => {
    if (!entries[name]) throw new Error("Missing technology logo: " + name);
    return entries[name];
  };
  window.TechStackLogos = Object.freeze({
    entries: Object.freeze(entries),
    get,
    markup(name) {
      return '<img class="tech-logo-image" src="' + get(name).src + '" alt="" width="128" height="128" draggable="false" />';
    },
  });
})();
`;

fs.writeFileSync(path.join(root, "tech-logos.js"), bundle);
console.log(`Bundled ${sources.length} technology logos.`);
